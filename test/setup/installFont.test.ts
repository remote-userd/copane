import { expect, test } from "bun:test"
import { mkdirSync, mkdtempSync, readFileSync, readdirSync, writeFileSync } from "node:fs"
import { tmpdir } from "node:os"
import { join } from "node:path"
import { FACE, FONT_FILES, OLD_FACE, configIconsEdit, terminalFontEdit, windowsFontScript } from "../../src/setup/installFont"
import { fontNames } from "../support/ttf"

const WT = `// This file was initially generated by Windows Terminal
{
    "$help": "https://aka.ms/terminal-documentation",
    "defaultProfile": "{2c4de342-38b7-51cf-b940-2309a097f518}",
    "profiles":
    {
        "defaults": {},
        "list":
        [
            {
                "guid": "{2c4de342-38b7-51cf-b940-2309a097f518}",
                "name": "Ubuntu", // my distro
            },
        ]
    },
    "schemes": [],
}
`

test("adds the face when none is set, keeping comments and trailing commas; second run is a no-op", () => {
  const r = terminalFontEdit(WT)
  expect(r.changed).toBe(true)
  expect(r.nerd).toBe(true)
  expect(r.text).toContain("// This file was initially generated")
  expect(r.text).toContain("// my distro")
  expect(r.text).toContain(`"face": "${FACE}"`)
  const again = terminalFontEdit(r.text)
  expect(again.changed).toBe(false)
  expect(again.nerd).toBe(true)
})

test("leaves a chosen font alone: Nerd faces count as done, others are not touched", () => {
  const nerd = WT.replace('"name": "Ubuntu",', '"name": "Ubuntu", "font": { "face": "JetBrainsMono NF" },')
  expect(terminalFontEdit(nerd)).toMatchObject({ changed: false, nerd: true })
  const custom = WT.replace('"defaults": {}', '"defaults": { "font": { "face": "Consolas" } }')
  const r = terminalFontEdit(custom)
  expect(r).toMatchObject({ changed: false, nerd: false })
  expect(r.reason).toContain("Consolas")
  expect(r.text).toBe(custom)
})

test("the old Mono face moves to the new one, in defaults and profiles; other fonts stay", () => {
  const old = WT.replace('"defaults": {}', `"defaults": { "font": { "face": "${OLD_FACE}" } }`).replace(
    '"name": "Ubuntu",',
    `"name": "Ubuntu", "fontFace": "${OLD_FACE}",`,
  )
  const r = terminalFontEdit(old)
  expect(r).toMatchObject({ changed: true, nerd: true })
  expect(r.text).not.toContain(OLD_FACE)
  expect(r.text).toContain(`"face": "${FACE}"`)
  expect(r.text).toContain(`"fontFace": "${FACE}"`)
  expect(r.text).toContain("// my distro")
  expect(terminalFontEdit(r.text).changed).toBe(false)
})

test("configIconsEdit turns icons on once and never overrides the user's choice", () => {
  const fresh = configIconsEdit(null)
  expect(JSON.parse(fresh.text)).toEqual({ tree: { icons: "nerd" } })
  const merged = configIconsEdit('{ "ai": { "command": "claude" } }')
  expect(JSON.parse(merged.text)).toEqual({ ai: { command: "claude" }, tree: { icons: "nerd" } })
  const mine = '{ "tree": { "icons": "simple" } }'
  expect(configIconsEdit(mine)).toEqual({ text: mine, changed: false })
})

test("windowsFontScript installs per user and registers each font", () => {
  const s = windowsFontScript([{ winPath: "C:\\x\\it's.ttf", file: "a.ttf", registry: "A Regular (TrueType)" }])
  expect(s).toContain("$env:LOCALAPPDATA 'Microsoft\\Windows\\Fonts'")
  expect(s).toContain("HKCU:\\Software\\Microsoft\\Windows NT\\CurrentVersion\\Fonts")
  expect(s).toContain("'A Regular (TrueType)'")
  expect(s).toContain("'C:\\x\\it''s.ttf'") // quotes escaped
})

test("the face name matches the bundled font's family name", async () => {
  const bytes = new Uint8Array(
    await Bun.file(join(import.meta.dir, "../../assets/fonts/CaskaydiaMonoNerdFont-Regular.ttf")).arrayBuffer(),
  )
  expect(fontNames(bytes).get(16)).toBe(FACE)
})

test("dry run on a copy of settings: font set, backup written, config created", () => {
  const dir = mkdtempSync(join(tmpdir(), "font-dry-"))
  const settings = join(dir, "settings.json")
  writeFileSync(settings, WT)
  const r = Bun.spawnSync(["bun", "run", join(import.meta.dir, "../../src/setup/installFont.ts")], {
    env: { ...process.env, CE_FONT_WT_SETTINGS: settings, CE_FONT_SKIP_INSTALL: "1", XDG_CONFIG_HOME: dir },
    stdout: "pipe",
  })
  const out = r.stdout.toString()
  expect(out).toContain("default font set to")
  expect(readFileSync(settings, "utf8")).toContain(FACE)
  expect(readdirSync(dir).some((f) => f.startsWith("settings.json.bak-"))).toBe(true)
  expect(JSON.parse(readFileSync(join(dir, "copane/config.json"), "utf8"))).toEqual({ tree: { icons: "nerd" } })
  const second = Bun.spawnSync(["bun", "run", join(import.meta.dir, "../../src/setup/installFont.ts")], {
    env: { ...process.env, CE_FONT_WT_SETTINGS: settings, CE_FONT_SKIP_INSTALL: "1", XDG_CONFIG_HOME: dir },
    stdout: "pipe",
  })
  expect(second.stdout.toString()).toContain("already uses a Nerd Font")
  expect(second.stdout.toString()).toContain("already set")
})

test("a finished setup is remembered: the next install skips PowerShell until something changed", () => {
  const dir = mkdtempSync(join(tmpdir(), "font-stamp-"))
  const settings = join(dir, "settings.json")
  writeFileSync(settings, WT.replace('"defaults": {}', `"defaults": { "font": { "face": "${FACE}" } }`))
  const stamp = { face: FACE, fonts: FONT_FILES.map((f) => f.file), settings: [settings] }
  mkdirSync(join(dir, "copane"))
  writeFileSync(join(dir, "copane/font-setup.json"), JSON.stringify(stamp))
  const run = (extra: Record<string, string> = {}) =>
    Bun.spawnSync(["bun", "run", join(import.meta.dir, "../../src/setup/installFont.ts")], {
      env: { ...process.env, CE_FONT_WT_SETTINGS: settings, XDG_CONFIG_HOME: dir, ...extra },
      stdout: "pipe",
    }).stdout.toString()
  expect(run()).toContain("already set up")
  // Someone picked another font: set up again (here with the install itself skipped).
  writeFileSync(settings, WT.replace('"defaults": {}', '"defaults": { "font": { "face": "Consolas" } }'))
  writeFileSync(join(dir, "copane/font-setup.json"), JSON.stringify(stamp))
  expect(run({ CE_FONT_SKIP_INSTALL: "1" })).not.toContain("already set up")
})
